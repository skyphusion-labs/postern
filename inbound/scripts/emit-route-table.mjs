// Emit the route contract for every seam that cannot import TypeScript (#417).
//
// inbound/src/routes.ts is the SOURCE. This projects it into the two files under
// contracts/ that the clients, the docs, and the worker's own tests read:
//
//   contracts/api-routes.json  the SPINE  (#449's shape, byte-compatible: which routes
//                              exist, which method reaches them, which scope each
//                              demands, and what guards the pre-gate ones)
//   contracts/api-params.json  the PARAMS (which query names and body keys each route
//                              reads, keyed by the same route id so the files join)
//
// Neither file is hand-edited: route-table.test.ts fails when a committed file and the
// source disagree, so a stale projection breaks the suite instead of quietly telling a
// client the wrong thing.
//
// Usage: npm run routes:emit   (Node >= 22 strips the TypeScript types natively)

import { writeFileSync } from "node:fs";
import { ROUTE_TABLE } from "../src/routes.ts";

const GENERATED = (also) => [
  "GENERATED by `npm run routes:emit` from inbound/src/routes.ts. Do not edit by hand:",
  "inbound/route-table.test.ts fails when this file and the source disagree.",
  ...also,
];

const spine = {
  $comment: GENERATED([
    "The worker's HTTP route table (#417/#449). One place where a route, its method,",
    "and the token scope it demands are written down for every seam: the worker",
    "validates itself against it (inbound/route-contract.test.ts drives the REAL",
    "handleApi), and each client asserts the paths it emits are paths the worker",
    "serves. Before this, every suite mocked its own idea of the worker, which is how",
    "the published clients drifted a feature generation behind with green tests.",
    "Adding a route means adding a row to inbound/src/routes.ts and re-emitting.",
    "scope: what requiredScope() demands; null means the route is not behind the bearer",
    "scope gate at all, and `auth` says what guards it instead.",
    "match: exact = the whole path; prefix = this path plus anything under it.",
  ]),
  version: 1,
  routes: ROUTE_TABLE.map((r) => ({
    id: r.id,
    method: r.method,
    path: r.path,
    match: r.match,
    scope: r.scope,
    auth: r.auth,
    ...(r.exclude ? { exclude: r.exclude } : {}),
    ...(r.requireChild ? { requireChild: true } : {}),
    ...(r.requireSeparator ? { requireSeparator: true } : {}),
    ...(r.template ? { template: r.template } : {}),
    ...(r.note ? { note: r.note } : {}),
  })),
};

const withParams = ROUTE_TABLE.filter((r) => r.query?.length || r.body?.length);
const params = {
  $comment: GENERATED([
    "The PARAMETER layer of the contract (#417), the sibling of api-routes.json, keyed",
    "by the same route id so the two join and neither repeats the other. It answers",
    "'what may a caller SEND to this route', which is the half the published clients",
    "actually drifted on: a filter the worker honors that no client can express, and a",
    "name a client sends that the worker never reads, are both invisible to a suite",
    "that mocks its own idea of the worker.",
    "Every claim here is proved against the REAL handler in inbound/route-params.test.ts:",
    "a declared query parameter must be strictly REFUSED when bogus or demonstrably",
    "CHANGE the answer, so this file cannot describe a worker that does not exist.",
    "query: query-string names the route reads. body: top-level JSON keys; 'set.x' names",
    "a nested key. A route with no entry here takes neither.",
  ]),
  version: 1,
  params: Object.fromEntries(
    withParams.map((r) => [
      r.id,
      {
        ...(r.query?.length ? { query: r.query } : {}),
        ...(r.body?.length ? { body: r.body } : {}),
        ...(r.note ? { note: r.note } : {}),
      },
    ]),
  ),
};

for (const [name, payload] of [["api-routes", spine], ["api-params", params]]) {
  const out = new URL(`../../contracts/${name}.json`, import.meta.url);
  writeFileSync(out, `${JSON.stringify(payload, null, 2)}\n`);
  console.log(`wrote ${out.pathname}`);
}
console.log(`${ROUTE_TABLE.length} routes, ${withParams.length} with parameters`);
